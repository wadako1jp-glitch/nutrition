def match(term):
    tokens = [t for t in term.split("・") if t]
    tokens_n = [norm(t) for t in tokens]
    best = None
    for code, name, nname in food_names:
        if all(t in nname for t in tokens_n):
            score = len(nname)  # 短いほど良い一致とみなす
            if best is None or score < best[2]:
                best = (code, name, score)
    return best

hit = 0
miss = []
for t in terms:
    m = match(t)
    if m:
        hit += 1
    else:
        miss.append(t)

print(f"{hit}/{len(terms)} 一致 ( {hit/len(terms)*100:.0f}% )")
print("---未ヒット---")
for t in miss:
    print(" -", t)
